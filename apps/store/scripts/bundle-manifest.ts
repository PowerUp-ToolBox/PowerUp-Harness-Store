/**
 * Bundles @harness-store/manifest for the Deno Edge Functions: its pure main entry and its npm
 * dependencies (semver, which is CommonJS, @cfworker/json-schema and fflate) as one ES module,
 * `supabase/functions/_shared/manifest.js`. An Edge Function sees only the files under
 * supabase/functions, both when served locally and when deployed, so it cannot import the
 * workspace package itself. The output is gitignored; `pnpm build` writes it, which `db:start`,
 * `functions:serve` and CI run first.
 *
 * The build fails on any Node built-in, so the bundle runs in Deno exactly as the entry runs in
 * the Electron renderer.
 */
import { builtinModules, createRequire } from 'node:module';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'vite';
import type { InlineConfig, Plugin } from 'vite';
import { storeRoot } from './local-stack.ts';

export const MANIFEST_BUNDLE = 'manifest.js';

function forbidNodeBuiltins(): Plugin {
  const builtins = new Set(builtinModules);
  return {
    name: 'forbid-node-builtins',
    enforce: 'pre',
    resolveId(source) {
      if (source.startsWith('node:') || builtins.has(source.split('/')[0] ?? '')) {
        this.error(`The Edge Function bundle imports the Node built-in "${source}"`);
      }
      return null;
    },
  };
}

/** The Vite configuration of the bundle; `write: false` keeps it in memory (for tests). */
export function bundleConfig(root: string = storeRoot(), write = true): InlineConfig {
  const require = createRequire(join(root, 'package.json'));
  return {
    root,
    configFile: false,
    publicDir: false,
    logLevel: 'warn',
    plugins: [forbidNodeBuiltins()],
    build: {
      write,
      outDir: join(root, 'supabase', 'functions', '_shared'),
      emptyOutDir: false,
      minify: false,
      target: 'es2022',
      lib: {
        entry: require.resolve('@harness-store/manifest'),
        formats: ['es'],
        fileName: () => MANIFEST_BUNDLE,
      },
      rolldownOptions: {
        output: {
          banner:
            '// Generated by apps/store/scripts/bundle-manifest.ts from @harness-store/manifest. Do not edit.',
        },
      },
    },
  };
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await build(bundleConfig());
}
